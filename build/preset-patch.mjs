/**
 * dsh-molbio-tools/build/preset-patch.mjs
 *
 * Generate the ONE bundle patch this package ships: the client anchor plus the
 * "Molecular Biology Lab" agent preset.
 *
 * WHY ONE FILE
 * ------------
 * DSH's runtime accepts `dsh.bundle.patch` as a file path or an ordered list of
 * file paths (`@deepseek-ai/dsh-app-boot` → `bundlePatchPaths`), and the shipped
 * `@deepseek-ai/dsh-web-app` uses the list form. DSH STORE's submission precheck
 * only accepts a single string (`safePatchPath`), so the two layers this package
 * used to ship as a list are emitted as one file with two top-level `insert`
 * operations, in the same order they were applied:
 *
 *     1. molbio-client      → './host.mjs'  (inert host anchor; see below)
 *     2. preset-molbio-lab  → '@deepseek-ai/dsh-agent-preset'
 *
 * Nothing about either layer changes: a patch file is an ordered list of
 * operations, and DSH applies them in file order exactly as it applied the two
 * files in list order.
 *
 * WHY THE ANCHOR EXISTS
 * ---------------------
 * DSH's client-module scan walks the HOST Loader tree only. It reads each live
 * host row's package manifest, takes `dsh.client` and `exports["./client"]` from
 * it, and composes the browser graph that becomes `window.__DSH_BOOT__`. A
 * preset's rows live in an isolated subtree that scan never visits.
 *
 * So when the tools moved into the preset, this package lost its only host-plane
 * row, its bundle stopped reaching the page, and the two right-sidebar tabs
 * (Molbio / Papers) silently disappeared. `host.mjs` restores exactly one inert
 * row so the browser half is discoverable again — without putting any tool into
 * a session that did not choose the molbio-lab mode.
 *
 * WHY THE PRESET IS GENERATED
 * ---------------------------
 * DSH 0.1.7-alpha.1 removed the `<dshHome>/.agent-presets` directory scan: a
 * preset is now a `@deepseek-ai/dsh-agent-preset` ROW in a bundle patch, which
 * is what the second insert below declares. Because the BUNDLE registers it,
 * `dsh plugin --profile <p> add dsh-molbio-tools` puts the mode in the picker
 * with no copy step and no preset-root patch — see README「安装」.
 *
 * Keeping the rows in ONE place and generating the container from them is what
 * stops the two from drifting, because `test/preset-health.mjs` validates every
 * row against the INSTALLED harness's own schemas.
 *
 *   source : preset/molbio-lab/agent.cordis.yml  (top-level row list, comments intact)
 *   source : preset/molbio-lab/preset.yml        (picker name + description)
 *   output : cordis.patch.yml                    (GENERATED; anchor + preset)
 *
 * The rows are emitted as-is: no re-serialization, so the comments that explain
 * each row survive and the file stays diffable against the shipped `standard`
 * patch it descends from.
 *
 * Usage:
 *   node build/preset-patch.mjs            # write the patch
 *   node build/preset-patch.mjs --check    # exit 1 when the committed patch is stale
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, '..');

/** The row list, with the source's own header comment block removed. */
export function rowBlockOf(source) {
  const lines = source.split(/\r?\n/);
  const first = lines.findIndex((line) => /^- /.test(line));
  if (first === -1) return undefined;
  return lines.slice(first).join('\n').replace(/\s*$/, '');
}

/** Indent every line of a block by `width` spaces. */
const indent = (block, width) => block.split('\n').map((line) => (line === '' ? line : ' '.repeat(width) + line)).join('\n');

const HEADER = [
  '# dsh-molbio-tools bundle patch — the one file `dsh.bundle.patch` names.',
  '#',
  '# GENERATED by build/preset-patch.mjs. Edit the row list in',
  '# preset/molbio-lab/agent.cordis.yml (and the picker strings in preset.yml), then',
  '# re-run `node build/preset-patch.mjs`; hand edits here are reverted by the next',
  '# run, and `node build/preset-patch.mjs --check` fails while the two disagree.',
  '#',
  '# Two top-level inserts, applied in this order:',
  '#   1. molbio-client      — inert host anchor for the browser half (see below)',
  '#   2. preset-molbio-lab  — the "Molecular Biology Lab" agent preset',
].join('\n');

const ANCHOR = [
  '# ── 1. the CLIENT-BUNDLE ANCHOR ────────────────────────────────────────────',
  '#',
  '# `host.mjs` registers no tool and publishes no service. Its only job is to be a',
  "# loader row DSH's client-module scan can see: that scan walks the HOST Loader",
  "# tree, reads the row's package manifest, and takes `dsh.client` +",
  '# `exports["./client"]` from it to compose `window.__DSH_BOOT__`. A preset\'s rows',
  '# live in an isolated subtree the scan never visits, so a `dsh.client` package',
  '# referenced only from inside a preset loses its only discoverable row and its',
  '# right-sidebar tabs silently disappear.',
  '#',
  '# Keep the tool in the PRESET and only the anchor here. An earlier version of',
  "# this file inserted a host row for the tool itself (`name: dsh-molbio-tools`),",
  "# which both registered all 60 tools globally and collided with the preset's own",
  '# copy of that row:',
  '#',
  '#     broken: "tool-molbio (...): never started"',
  '- insert:',
  '    - id: molbio-client',
  "      name: './host.mjs'",
].join('\n');

/**
 * Build the bundle patch: anchor first, preset second.
 *
 * @param {{rows: string, description: string, displayName?: string}} input
 * @returns {string} the complete `cordis.patch.yml` text (single trailing newline)
 */
export function buildPatch({ rows, description, displayName = 'Molecular Biology Lab' }) {
  const presetHeader = [
    '# ── 2. the MOLECULAR BIOLOGY LAB PRESET ───────────────────────────────────',
    '#',
    '# DSH 0.1.7-alpha.1 removed the `<dshHome>/.agent-presets` directory scan: a',
    '# preset is now a `@deepseek-ai/dsh-agent-preset` ROW in a bundle patch, which',
    '# is what this insert declares. Because the BUNDLE registers it,',
    '# `dsh plugin --profile <p> add dsh-molbio-tools` puts the mode in the picker',
    '# with no copy step and no preset-root patch — see README「安装」.',
    '#',
    '# `order: 5` is deliberate: the shipped presets occupy 1..4 (standard, ptc,',
    '# minimal, cordis) and the registry sorts by `order` with an id tie-break, so a',
    '# shared number would let the picker order depend on alphabetical accident.',
  ].join('\n');

  return [
    HEADER,
    '',
    ANCHOR,
    '',
    presetHeader,
    '- insert:',
    '    - id: preset-molbio-lab',
    "      name: '@deepseek-ai/dsh-agent-preset'",
    '      config:',
    '        id: molbio-lab',
    '        order: 5',
    `        name: ${displayName}`,
    `        description: ${JSON.stringify(description)}`,
    '        plugins:',
    indent(rows, 10),
    '',
  ].join('\n');
}

function main() {
  const check = process.argv.includes('--check');
  const sourcePath = join(repoRoot, 'preset', 'molbio-lab', 'agent.cordis.yml');
  const metaPath = join(repoRoot, 'preset', 'molbio-lab', 'preset.yml');
  const outPath = join(repoRoot, 'cordis.patch.yml');

  const rows = rowBlockOf(readFileSync(sourcePath, 'utf8'));
  if (rows === undefined || !rows.includes('- id:')) {
    console.error(`preset-patch: ${sourcePath} carries no top-level row list`);
    process.exit(2);
  }

  // The picker's display strings come from `preset.yml` (the same file the pre-
  // 0.1.7 directory mechanism read), NOT from the npm `description`: the latter
  // is a packaging blurb, while this one is the user-facing copy that
  // `test/preset-health.mjs` checks the tool count in.
  const meta = /^name:\s*(.+)$/m.exec(readFileSync(metaPath, 'utf8'));
  const description = /^description:\s*(.+)$/m.exec(readFileSync(metaPath, 'utf8'))?.[1];
  if (description === undefined) {
    console.error(`preset-patch: ${metaPath} carries no description line`);
    process.exit(2);
  }
  const text = buildPatch({ rows, description, displayName: meta?.[1]?.trim() });

  if (check) {
    let current;
    try {
      current = readFileSync(outPath, 'utf8');
    } catch {
      console.error(`preset-patch: ${outPath} does not exist — run \`node build/preset-patch.mjs\``);
      process.exit(1);
    }
    if (current !== text) {
      console.error('preset-patch: the committed bundle patch is STALE — run `node build/preset-patch.mjs`');
      process.exit(1);
    }
    console.log('bundle patch is current');
    return;
  }

  writeFileSync(outPath, text, 'utf8');
  const rowCount = rows.split('\n').filter((line) => /^\s*- id:/.test(line)).length;
  console.log(`bundle patch written: ${outPath} (${rowCount} preset rows + anchor)`);
}

if (process.argv[1] !== undefined && import.meta.url === pathToFileURLSafe(process.argv[1])) main();

/** `pathToFileURL` that tolerates a missing path (a bare REPL import). */
function pathToFileURLSafe(path) {
  try {
    return new URL(`file://${resolve(path).replace(/\\/g, '/')}`).href;
  } catch {
    return '';
  }
}
