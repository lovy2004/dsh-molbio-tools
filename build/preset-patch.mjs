/**
 * dsh-molbio-tools/build/preset-patch.mjs
 *
 * Generate the AGENT-PRESET bundle patch from the canonical row list.
 *
 * WHY THIS EXISTS
 * ---------------
 * DSH 0.1.7-alpha.1 replaced the preset DIRECTORY mechanism. Before it, a preset
 * was an `agent.cordis.yml` the harness discovered from `<dshHome>/.agent-presets`
 * or from a configured root (`@deepseek-ai/dsh-agent-presets` scanned
 * directories). That package is gone, and the registry that replaced it "neither
 * scans directories nor accepts preset paths" — a preset is now a
 * `@deepseek-ai/dsh-agent-preset` ROW inside a bundle patch:
 *
 *     - insert:
 *         - id: preset-molbio-lab
 *           name: '@deepseek-ai/dsh-agent-preset'
 *           config:
 *             id: molbio-lab
 *             name: Molecular Biology Lab
 *             description: ...
 *             plugins: [ ...the rows that used to be the composition... ]
 *
 * The rows themselves did not change — only their container did. Keeping the
 * rows in ONE place and generating the container from them is what stops the two
 * from drifting, because `test/preset-health.mjs` validates every row against
 * the INSTALLED harness's own schemas.
 *
 *   source : preset/molbio-lab/agent.cordis.yml  (top-level row list, comments intact)
 *   output : preset/molbio-lab/preset.patch.yml  (the bundle patch, GENERATED)
 *
 * The source is emitted as-is: no re-serialization, so the comments that explain
 * each row survive and the file stays diffable against the shipped `standard`
 * patch it descends from.
 *
 * Usage:
 *   node build/preset-patch.mjs            # write the patch
 *   node build/preset-patch.mjs --check    # exit 1 when the committed patch is stale
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, '..');

/** The row list, with the source's own header comment block removed. */
export function rowBlockOf(source) {
  const lines = source.split(/\r?\n/);
  const first = lines.findIndex((line) => /^- /.test(line));
  if (first === -1) return undefined;
  return lines.slice(first).join('\n').replace(/\s*$/, '');
}

/** Indent every line of a block by `width` spaces. */
const indent = (block, width) => block.split('\n').map((line) => (line === '' ? line : ' '.repeat(width) + line)).join('\n');

export function buildPatch({ rows, description, displayName = 'Molecular Biology Lab' }) {
  const header = [
    '# dsh-molbio-tools bundle layer: declares the "Molecular Biology Lab" agent preset.',
    '#',
    '# GENERATED by build/preset-patch.mjs from preset/molbio-lab/agent.cordis.yml.',
    '# Edit the ROW LIST there and re-run `node build/preset-patch.mjs`; editing the',
    "# `plugins:` block below by hand will be reverted by the next run, and",
    '# `node build/preset-patch.mjs --check` fails while the two disagree.',
    '#',
    '# DSH 0.1.7-alpha.1 removed the `<dshHome>/.agent-presets` directory scan: a preset is',
    '# now a `@deepseek-ai/dsh-agent-preset` ROW in a bundle patch, which is what this',
    '# layer inserts. Because the BUNDLE registers it, `dsh plugin --profile <p> add',
    '# dsh-molbio-tools` puts the mode in the picker with no copy step and no',
    '# preset-root patch — see README「安装」.',
  ].join('\n');

  return [
    header,
    '- insert:',
    '    - id: preset-molbio-lab',
    "      name: '@deepseek-ai/dsh-agent-preset'",
    '      config:',
    '        id: molbio-lab',
    '        order: 2',
    `        name: ${displayName}`,
    `        description: ${JSON.stringify(description)}`,
    '        plugins:',
    indent(rows, 10),
    '',
  ].join('\n');
}

function main() {
  const check = process.argv.includes('--check');
  const sourcePath = join(repoRoot, 'preset', 'molbio-lab', 'agent.cordis.yml');
  const metaPath = join(repoRoot, 'preset', 'molbio-lab', 'preset.yml');
  const outPath = join(repoRoot, 'preset', 'molbio-lab', 'preset.patch.yml');

  const rows = rowBlockOf(readFileSync(sourcePath, 'utf8'));
  if (rows === undefined || !rows.includes('- id:')) {
    console.error(`preset-patch: ${sourcePath} carries no top-level row list`);
    process.exit(2);
  }

  // The picker's display strings come from `preset.yml` (the same file the pre-
  // 0.1.7 directory mechanism read), NOT from the npm `description`: the latter
  // is a packaging blurb, while this one is the user-facing copy that
  // `test/preset-health.mjs` checks the tool count in.
  const meta = /^name:\s*(.+)$/m.exec(readFileSync(metaPath, 'utf8'));
  const description = /^description:\s*(.+)$/m.exec(readFileSync(metaPath, 'utf8'))?.[1];
  if (description === undefined) {
    console.error(`preset-patch: ${metaPath} carries no description line`);
    process.exit(2);
  }
  const text = buildPatch({ rows, description, displayName: meta?.[1]?.trim() });

  if (check) {
    let current;
    try {
      current = readFileSync(outPath, 'utf8');
    } catch {
      console.error(`preset-patch: ${outPath} does not exist — run \`node build/preset-patch.mjs\``);
      process.exit(1);
    }
    if (current !== text) {
      console.error('preset-patch: the committed preset patch is STALE — run `node build/preset-patch.mjs`');
      process.exit(1);
    }
    console.log('preset patch is current');
    return;
  }

  writeFileSync(outPath, text, 'utf8');
  const rows_ = rows.split('\n').filter((line) => /^\s*- id:/.test(line)).length;
  console.log(`preset patch written: ${outPath} (${rows_} rows)`);
}

if (process.argv[1] !== undefined && import.meta.url === pathToFileURLSafe(process.argv[1])) main();

/** `pathToFileURL` that tolerates a missing path (a bare REPL import). */
function pathToFileURLSafe(path) {
  try {
    return new URL(`file://${resolve(path).replace(/\\/g, '/')}`).href;
  } catch {
    return '';
  }
}
